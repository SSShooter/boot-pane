package config

// promptEN 是英文 prompt。
//
// 与 promptZH 逐条对应：只翻措辞，规则一条不少也一条不多。
// 改任何一条规则时，四份文件要一起改。
func promptEN(p ResolvedProject, shell string) string {
	return joinPrompt([]string{
		"I want to set up BootPane launch buttons for the project below. BootPane is a project launcher: one button runs one long-running startup command.",
		"",
		"Project root:",
		"    " + p.Path,
		"",
		"Read the files in this directory (package.json, go.mod, docker-compose.yml, Makefile, vite.config.*,",
		".env*, any lockfile). Every command must come from what you actually read, do not guess from experience.",
		"",
		"[What to look for]",
		"Find the process entry points that need to keep running: dev servers, watchers, mock services, backend APIs. One task per entry point.",
		"Do not list one-off tasks — install, build, lint, test, formatting and the like exit when they finish and do not belong in a launcher.",
		"",
		"[How to fill in the commands]",
		"- Pick the package manager from the lockfile: pnpm-lock.yaml means pnpm, yarn.lock means yarn,",
		"  package-lock.json means npm, bun.lockb means bun. Do not default to npm.",
		"- command may only hold a script name that already exists in package.json scripts (e.g. pnpm dev:h5),",
		"  or an executable that really exists in the repository. If you cannot read it, do not write it.",
		"- cwd is the subdirectory the command runs in, relative to the project root, and it must really exist;",
		"  do not start it with / and do not climb out with .. . Leave it an empty string to run in the root.",
		"- To change the port or pass arguments use the env field, never stuff them into command.",
		"",
		"[Where to find ports]",
		"Check in order: server.port in vite.config.* / webpack.config.*, --port in package.json scripts,",
		"PORT or VITE_PORT in .env*, ports in docker-compose.yml,",
		"and application.yml / config.toml / appsettings.json on the backend.",
		"If you cannot find one, do not write a port.",
		"",
		"[Readiness check waitFor]",
		"BootPane uses it to decide that startup is complete; pick one of the three, highest priority first:",
		"1. Text in the startup output that appears reliably and only once ready (preferred, hardest to get wrong):",
		`   { "type": "log", "log": "ready in", "timeout": 120 }`,
		"   log is a case-sensitive plain substring match, not a regex, do not change the casing.",
		"   Reliable markers: vite's ready in, WXT's Started dev server,",
		"   Spring's Started ... in, a Go service's listening on. Copy the line from the output verbatim, do not paraphrase.",
		"2. A port number you are sure of (actually read from a config file or the startup output):",
		`   { "type": "port", "port": 5173, "timeout": 60 }`,
		"   The port probe dials both IPv4 and IPv6, so services bound only to [::1] are still detected correctly.",
		"3. Unsure about both: omit the waitFor field entirely.",
		"timeout is in seconds. Prefer downgrading to log or omitting it over writing an unverified port —",
		"a wrong guess marks the task failed while the process is in fact still running.",
		"",
		"[Page URL openUrl]",
		"If this task serves a page people open in a browser (web app / h5 / admin console), put the address in openUrl",
		"and the card will show an \"Open page\" button. Build the address from the real port, e.g. http://localhost:5173.",
		"https, domains behind a reverse proxy and addresses with a path (like /admin) cannot be inferred; if you read them, write them explicitly.",
		"Do not set openUrl for backend APIs, mock services or tasks that only produce build artifacts; if you are unsure about the port, omit it entirely.",
		"",
		"[Runtime environment]",
		"Commands are executed by " + shell + ", which has a few hard constraints:",
		"- Do not write prefix assignments like PORT=5173 pnpm dev, cmd does not accept them, use the env field instead",
		"- Do not use single quotes, and do not background a command with &",
		"- Avoid double quotes inside commands, the shell swallows one layer of them",
		"- One command per task, do not chain several services with && or ;",
		"",
		"[Hard requirements]",
		"1. id uses only lowercase letters, digits and hyphens, and is unique within the project.",
		"2. label is the name shown on the button, written in the user's language.",
		"3. group categorises the buttons, for example frontend / backend / mini program.",
		"4. Two tasks must not use the same port.",
		"5. Keep the task count between 1 and 5, only the entry points that really need to stay running.",
		`6. If this project has no long-running entry point at all, output an empty tasks array [],`,
		"   do not invent commands just to fill it up.",
		"",
		"[Project info]",
		"The top level also has a project object describing the project itself:",
		`- name: the project name. Prefer package.json's name or the README title, then the directory name, do not make one up.`,
		"- description: one sentence on what this project is and which long-running entry points it has, 40 words at most.",
		"  Distil it from the opening paragraphs of the README or package.json's description, do not copy a whole block.",
		"  If you cannot find anything usable, omit the description field entirely, do not make it up.",
		"",
		"[Output]",
		"Output only one json code block, no explanatory text, no comments. The structure is:",
		"",
		"{",
		`  "version": 1,`,
		`  "project": {`,
		`    "name": "my-shop",`,
		`    "description": "uni-app storefront: h5 frontend + Go API backend, two long-running processes"`,
		"  },",
		`  "tasks": [`,
		"    {",
		`      "id": "web",`,
		`      "label": "Start web app",`,
		`      "group": "Frontend",`,
		`      "command": "pnpm dev:h5",`,
		`      "cwd": "",`,
		`      "env": { "PORT": "5173" },`,
		`      "waitFor": { "type": "log", "log": "ready in", "timeout": 120 },`,
		`      "openUrl": "http://localhost:5173"`,
		"    },",
		"    {",
		`      "id": "api",`,
		`      "label": "Start backend",`,
		`      "group": "Backend",`,
		`      "command": "go run ./cmd/api",`,
		`      "cwd": "server",`,
		`      "waitFor": { "type": "log", "log": "listening on", "timeout": 60 }`,
		"    }",
		"  ]",
		"}",
		"",
		"Fields at a glance: id / label / group / command / cwd / env / waitFor / openUrl,",
		"where group, cwd, env, waitFor and openUrl are all optional.",
		"project is optional too: a missing name falls back to the directory name, a missing description is simply not shown.",
	})
}
