package config

// promptRU 是俄语 prompt。
//
// 与 promptZH 逐条对应：只翻措辞，规则一条不少也一条不多。
// 改任何一条规则时，四份文件要一起改。
func promptRU(p ResolvedProject, shell string) string {
	return joinPrompt([]string{
		"Хочу настроить кнопки запуска BootPane для проекта ниже. BootPane — это лаунчер проектов: одна кнопка запускает одну долго работающую команду.",
		"",
		"Корень проекта:",
		"    " + p.Path,
		"",
		"Прочитай файлы в этом каталоге (package.json, go.mod, docker-compose.yml, Makefile, vite.config.*,",
		".env*, любые lock-файлы). Каждая команда должна опираться на то, что ты действительно прочитал, не угадывай по опыту.",
		"",
		"[Что искать]",
		"Найди точки входа, которые должны работать постоянно: dev-серверы, watcher'ы, mock-сервисы, backend API. Одна задача на одну точку входа.",
		"Не включай одноразовые задачи — install, build, lint, test, форматирование и подобные завершаются сами и в лаунчере не нужны.",
		"",
		"[Как заполнять команды]",
		"- Пакетный менеджер выбирай по lock-файлу: pnpm-lock.yaml — это pnpm, yarn.lock — yarn,",
		"  package-lock.json — npm, bun.lockb — bun. Не используй npm по умолчанию.",
		"- command может содержать только имя скрипта, который уже есть в package.json scripts (например, pnpm dev:h5),",
		"  или исполняемый файл, который действительно есть в репозитории. Не прочитал — не пиши.",
		"- cwd — подкаталог, где выполняется команда, относительно корня проекта, и он должен реально существовать;",
		"  не начинай с / и не поднимайся через .. . Чтобы запускать в корне, оставь пустую строку.",
		"- Для смены порта или передачи аргументов используй поле env, никогда не встраивай их в command.",
		"",
		"[Где искать порт]",
		"Смотри по порядку: server.port в vite.config.* / webpack.config.*, --port в скриптах package.json,",
		"PORT или VITE_PORT в .env*, ports в docker-compose.yml,",
		"а на бэкенде — application.yml / config.toml / appsettings.json.",
		"Не нашёл — не пиши порт.",
		"",
		"[Признак готовности waitFor]",
		"По нему BootPane понимает, что запуск завершён; выбери один из трёх вариантов, приоритет сверху вниз:",
		"1. Текст в выводе, который появляется стабильно и только после готовности (предпочтительно, меньше всего ложных срабатываний):",
		`   { "type": "log", "log": "ready in", "timeout": 120 }`,
		"   log — это поиск подстроки с учётом регистра, а не регулярное выражение, не меняй регистр.",
		"   Надёжные маркеры: ready in у vite, Started dev server у WXT,",
		"   Started ... in у Spring, listening on у сервисов на Go. Копируй строку из вывода дословно, без пересказа.",
		"2. Номер порта, в котором ты уверен (реально прочитан из конфига или из вывода):",
		`   { "type": "port", "port": 5173, "timeout": 60 }`,
		"   Проверка порта идёт и по IPv4, и по IPv6, поэтому сервисы, слушающие только [::1], тоже определяются корректно.",
		"3. Не уверен ни в том, ни в другом: опусти поле waitFor целиком.",
		"timeout задаётся в секундах. Лучше перейти на log или опустить поле, чем указать непроверенный порт —",
		"ошибка пометит задачу как упавшую, хотя процесс на самом деле работает.",
		"",
		"[Адрес страницы openUrl]",
		"Если задача отдаёт страницу, которую открывают в браузере (веб / h5 / админка), запиши адрес в openUrl",
		"и на карточке появится кнопка «Открыть страницу». Собирай адрес по реальному порту, например http://localhost:5173.",
		"https, домены за обратным прокси и адреса с путём (вроде /admin) вывести нельзя; если прочитал — укажи явно.",
		"Не заполняй openUrl для backend API, mock-сервисов и задач, которые только собирают артефакты; если порт неясен, опусти поле целиком.",
		"",
		"[Среда выполнения]",
		"Команды выполняет " + shell + ", и у него есть жёсткие ограничения:",
		"- Не пиши присваивания перед командой вида PORT=5173 pnpm dev, cmd их не понимает, используй поле env",
		"- Не используй одинарные кавычки и не отправляй команду в фон через &",
		"- Избегай двойных кавычек внутри команды, shell съедает один уровень",
		"- Одна задача — одна команда, не соединяй несколько сервисов через && или ;",
		"",
		"[Жёсткие требования]",
		"1. id состоит только из строчных латинских букв, цифр и дефисов и уникален внутри проекта.",
		"2. label — имя на кнопке, на языке пользователя.",
		"3. group группирует кнопки, например frontend / backend / мини-программа.",
		"4. Две задачи не должны использовать один и тот же порт.",
		"5. Держи количество задач в пределах 1–5, только те точки входа, которым действительно нужно работать постоянно.",
		`6. Если в проекте нет ни одной долго работающей точки входа, выведи пустой массив tasks [],`,
		"   не придумывай команды ради заполнения.",
		"",
		"[Информация о проекте]",
		"На верхнем уровне есть ещё объект project, описывающий сам проект:",
		`- name: название проекта. Сначала возьми name из package.json или заголовок README, затем имя каталога, не придумывай своё.`,
		"- description: одно предложение о том, что это за проект и какие постоянные точки входа у него есть, не больше 40 слов.",
		"  Сформулируй по первым абзацам README или по description в package.json, не копируй целый блок.",
		"  Если ничего пригодного нет, опусти поле description целиком, не выдумывай.",
		"",
		"[Вывод]",
		"Выведи только один блок кода json, без пояснений и комментариев. Структура:",
		"",
		"{",
		`  "version": 1,`,
		`  "project": {`,
		`    "name": "my-shop",`,
		`    "description": "Магазин на uni-app: фронтенд h5 + backend API на Go, два постоянных процесса"`,
		"  },",
		`  "tasks": [`,
		"    {",
		`      "id": "web",`,
		`      "label": "Запустить веб",`,
		`      "group": "Фронтенд",`,
		`      "command": "pnpm dev:h5",`,
		`      "cwd": "",`,
		`      "env": { "PORT": "5173" },`,
		`      "waitFor": { "type": "log", "log": "ready in", "timeout": 120 },`,
		`      "openUrl": "http://localhost:5173"`,
		"    },",
		"    {",
		`      "id": "api",`,
		`      "label": "Запустить backend",`,
		`      "group": "Бэкенд",`,
		`      "command": "go run ./cmd/api",`,
		`      "cwd": "server",`,
		`      "waitFor": { "type": "log", "log": "listening on", "timeout": 60 }`,
		"    }",
		"  ]",
		"}",
		"",
		"Поля: id / label / group / command / cwd / env / waitFor / openUrl,",
		"причём group, cwd, env, waitFor и openUrl можно опускать.",
		"project тоже необязателен: без name подставляется имя каталога, без description ничего не показывается.",
	})
}
