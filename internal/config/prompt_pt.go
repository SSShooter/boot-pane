package config

// promptPT 是葡萄牙语（巴西）prompt。
//
// 与 promptZH 逐条对应：只翻措辞，规则一条不少也一条不多。
// 改任何一条规则时，四份文件要一起改。
func promptPT(p ResolvedProject, shell string) string {
	return joinPrompt([]string{
		"Quero configurar os botões de inicialização do BootPane para o projeto abaixo. O BootPane é um inicializador de projetos: cada botão executa um comando de longa duração.",
		"",
		"Raiz do projeto:",
		"    " + p.Path,
		"",
		"Leia os arquivos deste diretório (package.json, go.mod, docker-compose.yml, Makefile, vite.config.*,",
		".env*, qualquer lockfile). Todo comando deve vir do que você realmente leu, não chute pela experiência.",
		"",
		"[O que procurar]",
		"Encontre os pontos de entrada que precisam continuar rodando: dev servers, watchers, serviços de mock, APIs de backend. Uma tarefa por ponto de entrada.",
		"Não liste tarefas de uso único — install, build, lint, test, formatação e afins terminam ao acabar e não pertencem a um inicializador.",
		"",
		"[Como preencher os comandos]",
		"- Escolha o gerenciador de pacotes pelo lockfile: pnpm-lock.yaml é pnpm, yarn.lock é yarn,",
		"  package-lock.json é npm, bun.lockb é bun. Não use npm por padrão.",
		"- command só pode conter o nome de um script que já exista em package.json scripts (ex.: pnpm dev:h5),",
		"  ou um executável que realmente exista no repositório. Se não conseguir ler, não escreva.",
		"- cwd é a subpasta onde o comando roda, relativa à raiz do projeto, e precisa existir de verdade;",
		"  não comece com / e não suba com .. . Deixe como string vazia para rodar na raiz.",
		"- Para mudar a porta ou passar argumentos use o campo env, nunca coloque isso dentro de command.",
		"",
		"[Onde encontrar as portas]",
		"Verifique nesta ordem: server.port em vite.config.* / webpack.config.*, --port nos scripts do package.json,",
		"PORT ou VITE_PORT em .env*, ports no docker-compose.yml,",
		"e application.yml / config.toml / appsettings.json no backend.",
		"Se não encontrar, não escreva porta.",
		"",
		"[Critério de prontidão waitFor]",
		"O BootPane usa esse campo para decidir que a inicialização terminou; escolha uma das três, da prioridade mais alta para a mais baixa:",
		"1. Um texto na saída que aparece de forma confiável e só depois de ficar pronto (preferido, o menos sujeito a erro):",
		`   { "type": "log", "log": "ready in", "timeout": 120 }`,
		"   log é busca de substring literal e diferencia maiúsculas de minúsculas, não é regex, não mude a caixa.",
		"   Marcadores confiáveis: ready in do vite, Started dev server do WXT,",
		"   Started ... in do Spring, listening on de serviços Go. Copie a linha da saída literalmente, sem parafrasear.",
		"2. Um número de porta com certeza (lido de fato de um arquivo de configuração ou da saída):",
		`   { "type": "port", "port": 5173, "timeout": 60 }`,
		"   A sonda de porta testa IPv4 e IPv6, então serviços ligados só em [::1] ainda são detectados corretamente.",
		"3. Sem certeza de nenhum dos dois: omita o campo waitFor por inteiro.",
		"timeout é em segundos. Prefira cair para log ou omitir a escrever uma porta não verificada —",
		"um chute errado marca a tarefa como falha enquanto o processo na verdade continua rodando.",
		"",
		"[Endereço da página openUrl]",
		"Se esta tarefa serve uma página que se abre no navegador (web / h5 / painel administrativo), coloque o endereço em openUrl",
		"e o cartão mostrará um botão \"Abrir página\". Monte o endereço com a porta real, por exemplo http://localhost:5173.",
		"https, domínios atrás de proxy reverso e endereços com caminho (como /admin) não podem ser deduzidos; se você os leu, escreva explicitamente.",
		"Não preencha openUrl para APIs de backend, serviços de mock ou tarefas que só geram artefatos de build; se não tiver certeza da porta, omita por inteiro.",
		"",
		"[Ambiente de execução]",
		"Os comandos são executados por " + shell + ", que tem algumas restrições rígidas:",
		"- Não escreva atribuições de prefixo como PORT=5173 pnpm dev, o cmd não aceita, use o campo env",
		"- Não use aspas simples e não jogue o comando para segundo plano com &",
		"- Evite aspas duplas dentro dos comandos, o shell engole uma camada delas",
		"- Um comando por tarefa, não encadeie vários serviços com && ou ;",
		"",
		"[Requisitos obrigatórios]",
		"1. id usa apenas letras minúsculas, dígitos e hífens, e é único dentro do projeto.",
		"2. label é o nome mostrado no botão, escrito no idioma do usuário.",
		"3. group classifica os botões, por exemplo frontend / backend / miniprograma.",
		"4. Duas tarefas não podem usar a mesma porta.",
		"5. Mantenha de 1 a 5 tarefas, só os pontos de entrada que realmente precisam ficar rodando.",
		`6. Se o projeto não tiver nenhum ponto de entrada de longa duração, envie tasks como array vazio [],`,
		"   não invente comandos só para preencher.",
		"",
		"[Informações do projeto]",
		"No nível superior há também um objeto project descrevendo o próprio projeto:",
		`- name: o nome do projeto. Prefira o name do package.json ou o título do README, depois o nome da pasta, não invente um.`,
		"- description: uma frase dizendo o que é o projeto e quais pontos de entrada constantes ele tem, no máximo 40 palavras.",
		"  Extraia dos primeiros parágrafos do README ou do description do package.json, não copie um bloco inteiro.",
		"  Se não achar nada utilizável, omita o campo description por inteiro, não invente.",
		"",
		"[Saída]",
		"Envie apenas um bloco de código json, sem texto explicativo e sem comentários. A estrutura é:",
		"",
		"{",
		`  "version": 1,`,
		`  "project": {`,
		`    "name": "my-shop",`,
		`    "description": "Loja uni-app: frontend h5 + API Go no backend, dois processos residentes"`,
		"  },",
		`  "tasks": [`,
		"    {",
		`      "id": "web",`,
		`      "label": "Iniciar web",`,
		`      "group": "Frontend",`,
		`      "command": "pnpm dev:h5",`,
		`      "cwd": "",`,
		`      "env": { "PORT": "5173" },`,
		`      "waitFor": { "type": "log", "log": "ready in", "timeout": 120 },`,
		`      "openUrl": "http://localhost:5173"`,
		"    },",
		"    {",
		`      "id": "api",`,
		`      "label": "Iniciar backend",`,
		`      "group": "Backend",`,
		`      "command": "go run ./cmd/api",`,
		`      "cwd": "server",`,
		`      "waitFor": { "type": "log", "log": "listening on", "timeout": 60 }`,
		"    }",
		"  ]",
		"}",
		"",
		"Campos: id / label / group / command / cwd / env / waitFor / openUrl,",
		"sendo que group, cwd, env, waitFor e openUrl são todos opcionais.",
		"project também é opcional: sem name usa-se o nome da pasta, sem description nada é exibido.",
	})
}
